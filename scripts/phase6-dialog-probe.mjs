import {spawn} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
import {setTimeout,clearTimeout} from 'node:timers';
import path from 'node:path';
const evidence=path.resolve('docs/phase6/dialog-privacy/visible-'+new Date().toISOString().replaceAll(':','-'));
await mkdir(evidence,{recursive:true});
const exe=path.resolve('src-tauri/target/debug/examples/dialog_lifecycle_probe.exe');
const child=spawn(exe,[],{windowsHide:false,cwd:process.cwd()});
let output='',helperOutput='',timedOut=false;
child.stdout.on('data',bytes=>{output+=bytes;process.stdout.write(bytes);});child.stderr.on('data',bytes=>{output+=bytes;process.stderr.write(bytes);});
const args=['-NoProfile','-File',path.resolve('scripts/phase6-native-dialog.ps1'),'-OwnerPid',String(child.pid),'-FileName',path.resolve('tests/fixtures/demo.csv')];
const helper=spawn('powershell.exe',args,{windowsHide:true});
helper.stdout.on('data',bytes=>{helperOutput+=bytes;process.stdout.write(bytes);});helper.stderr.on('data',bytes=>{helperOutput+=bytes;process.stderr.write(bytes);});
const timer=setTimeout(()=>{timedOut=true;child.kill();helper.kill();},20000);
const close=process=>new Promise((resolve,reject)=>{process.on('error',reject);process.on('close',(exitCode,signal)=>resolve({exitCode,signal,pid:process.pid}));});
const [probeResult,helperResult]=await Promise.all([close(child),close(helper)]);
clearTimeout(timer);
const completed=!timedOut&&probeResult.exitCode===0&&helperResult.exitCode===0&&output.includes('result_count=Ok(1)');
await writeFile(path.join(evidence,'probe.log'),output);
await writeFile(path.join(evidence,'helper.log'),helperOutput);
await writeFile(path.join(evidence,'result.json'),JSON.stringify({exe,probeResult,helperResult,timedOut,completed,scope:'isolated fictional fixture; NOT product acceptance'},null,2)+'\n');
console.log(JSON.stringify({evidence,completed,timedOut}));
if(!completed)process.exitCode=1;
