import {spawn} from 'node:child_process';
import {writeFile} from 'node:fs/promises';
import {setTimeout,clearTimeout} from 'node:timers';
import path from 'node:path';
const exe=path.resolve('src-tauri/target/debug/deps/fileflow_desktop-317ca1a06b5a7fbb.exe');
const focused=process.argv.includes('--batch-focus');
const args=focused?['--exact','grants::tests::batch_admission_is_atomic_and_count_bounded','--nocapture','--test-threads=1']:['--test-threads=1'];
const child=spawn(exe,args,{windowsHide:true});
const expectedTests=focused?1:22,started=Date.now();
let output='',timedOut=false;child.stdout.on('data',data=>{output+=data;process.stdout.write(data);});child.stderr.on('data',data=>{output+=data;process.stderr.write(data);});
const timer=setTimeout(()=>{timedOut=true;child.kill();},focused?45000:180000);
const result=await new Promise((resolve,reject)=>{child.on('error',reject);child.on('close',(exitCode,signal)=>resolve({exitCode,signal,pid:child.pid}));});
clearTimeout(timer);
const complete=new RegExp(`test result: ok\\. ${expectedTests} passed; 0 failed; 0 ignored`).test(output)&&!output.includes('SKIP:')&&!timedOut;
const evidence=focused?'native-batch-focus':'native-direct-resumed';
await writeFile(`docs/phase6/final-validation/${evidence}.log`,output);
await writeFile(`docs/phase6/final-validation/${evidence}.json`,JSON.stringify({...result,exe,args,complete,timedOut,elapsedMs:Date.now()-started,expectedTests},null,2)+'\n');
console.log(JSON.stringify({...result,complete,timedOut,elapsedMs:Date.now()-started,expectedTests}));
if(result.exitCode!==0||!complete)process.exitCode=1;
